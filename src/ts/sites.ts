export interface RadarSite {
  id: string; // e.g. "02" for Melbourne
  name: string;
  lat: number;
  lon: number;
  state: string;
  sizes: Record<number, string>; // km -> product ID e.g. { 64: "IDR024", 128: "IDR023", 256: "IDR022", 512: "IDR021" }
}

// Extracted from BOM image map and radar pages
// Product ID scheme: IDR{site}{size} where size: 1=512km, 2=256km, 3=128km, 4=64km

// Sites that do NOT have a 64km product
const NO_64KM = new Set([
  "07", "14", "16", "23", "24", "25", "27", "28", "29",
  "36", "41", "44", "46", "53", "55", "56", "62", "67",
]);

export function getSizeProducts(id: string): Record<number, string> {
  const sizes: Record<number, string> = {
    128: `IDR${id}3`,
    256: `IDR${id}2`,
    512: `IDR${id}1`,
  };
  if (!NO_64KM.has(id)) {
    sizes[64] = `IDR${id}4`;
  }
  return sizes;
}

